package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/joyautomation/nautilus/plcnext"
)

// `naut plcnext import` writes a manifest that parses and a tag file for
// it; a re-run is byte-identical; it will not overwrite the hand-kept
// example manifest without --force.
func TestPlcnextImportCLI(t *testing.T) {
	devs, err := filepath.Abs("../../examples/plcnext-bench/plcnext_devices.yaml")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	run := func(extra ...string) int {
		return runPlcnext(append(append([]string{"import", "--transport", "shm", "--out", dir}, extra...), devs))
	}
	if rc := run(); rc != 0 {
		t.Fatalf("import rc=%d", rc)
	}
	raw, err := os.ReadFile(filepath.Join(dir, "plcnext_manifest.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(raw), "# Generated by `naut plcnext import plcnext_devices.yaml --transport shm`") {
		t.Errorf("header: %.120s", raw)
	}
	m, err := plcnext.ParseManifest(raw)
	if err != nil {
		t.Fatal(err)
	}
	if len(m.Modules) != 4 || len(m.Tags) != 36 || m.Transport != plcnext.TransportShm {
		t.Errorf("manifest: %d modules, %d tags, transport %s", len(m.Modules), len(m.Tags), m.Transport)
	}
	tags, err := os.ReadFile(filepath.Join(dir, "tags", "plcnext.yaml"))
	if err != nil || !strings.Contains(string(tags), `name: DO_15, role: output, init: false, desc: "slot 1 output 16"`) {
		t.Errorf("tag file: %v\n%s", err, tags)
	}
	if rc := run(); rc != 0 {
		t.Errorf("a re-run of the same list should be fine: rc=%d", rc)
	}
	// Into the example, beside the hand-kept manifest: refused.
	example := filepath.Dir(devs)
	before, _ := os.ReadFile(filepath.Join(example, "plcnext_manifest.yaml"))
	if rc := runPlcnext([]string{"import", "--transport", "shm", "--out", example, devs}); rc == 0 {
		t.Error("overwrote the hand-kept manifest without --force")
	}
	if after, _ := os.ReadFile(filepath.Join(example, "plcnext_manifest.yaml")); string(after) != string(before) {
		t.Fatal("the example manifest changed")
	}
	if rc := runPlcnext([]string{"import", "--transport", "udp", "--out", dir, devs}); rc == 0 {
		t.Error("a bad transport accepted")
	}
}
