package optommp

// modbusmap.go turns a scanned chassis into the two files a nautilus
// project consumes: a modbus_manifest.yaml the `modbus` driver polls and a
// tag file to compose. The processor's Modbus/TCP server (form 1678,
// chapter 4 and "groov I/O and High-Density Digital Module Register Table")
// lays its I/O out in fixed 64-channel-per-module strides, 1-based in the
// guide, 0-based PDU addresses here:
//
//	digital state   coil / discrete  512 + slot*64 + ch         (guide: 513 + …)
//	analog value    input register   4608 + (slot*64 + ch)*2    (guide: 4609 + …), float32
//	analog output   holding register 1030 + (slot*64 + ch)*2    (guide: 1031 + …), float32
//
// Verified on the bench GRV-EPIC-PR1 (2026-10-23): the ICTD probe in slot 2
// read 19.7 °C at input 4864 and 20.2 °C over OptoMMP at the same moment.
// Unit id does not matter to the processor; the generator writes 1.

import (
	"fmt"
	"strings"

	"github.com/joyautomation/nautilus/internal/tagfile"
	"github.com/joyautomation/nautilus/modbus"
)

const (
	modbusDigitalBase = 512
	modbusAnalogIn    = 4608
	modbusAnalogOut   = 1030
	modbusModuleSpan  = 64
)

// MapOptions steer Generate.
type MapOptions struct {
	// ID is the manifest source id and the tag-name prefix ("EPIC").
	ID string
	// Host is the processor's address; Port its Modbus port (0 = 502).
	Host string
	Port int
}

// Output is one generation: the manifest plus tag-file metadata.
type Output struct {
	Manifest modbus.Manifest
	Tags     []tagfile.Tag
}

// Generate maps every configured I/O channel of the chassis onto the
// processor's Modbus tables. Tag names are <ID>_M<slot>_<Kind><channel>:
// EPIC_M0_DI03, EPIC_M2_AI00. Comm channels and unknown families are
// skipped — they have no Modbus face. The result passes
// modbus.Manifest.Validate.
func Generate(ch Chassis, opts MapOptions) (Output, error) {
	if opts.ID == "" {
		return Output{}, fmt.Errorf("optommp: an id is required (the source id and tag prefix)")
	}
	if opts.Host == "" {
		return Output{}, fmt.Errorf("optommp: a host is required")
	}
	out := Output{}
	out.Manifest.Sources = []modbus.Source{{ID: opts.ID, Host: opts.Host, Port: opts.Port, UnitID: 1}}
	for _, m := range ch.Modules {
		for _, c := range m.Channels {
			name := fmt.Sprintf("%s_M%d_%s%02d", opts.ID, m.Slot, c.Kind, c.Index)
			desc := fmt.Sprintf("%s slot %d ch %d — %s", m.Part, m.Slot, c.Index, c.Desc)
			point := uint16(m.Slot*modbusModuleSpan + c.Index)
			var b modbus.TagBinding
			tag := tagfile.Tag{Name: name, Role: "input", Unit: c.Unit, Desc: desc}
			switch c.Kind {
			case KindDI:
				b = modbus.TagBinding{Table: modbus.TableDiscrete, Address: modbusDigitalBase + point, Format: "bool"}
			case KindDO:
				b = modbus.TagBinding{Table: modbus.TableCoil, Address: modbusDigitalBase + point, Format: "bool", Writable: true}
				tag.Role, tag.Init = "output", false
			case KindAI:
				b = modbus.TagBinding{Table: modbus.TableInput, Address: modbusAnalogIn + point*2, Format: "float32"}
			case KindAO:
				b = modbus.TagBinding{Table: modbus.TableHolding, Address: modbusAnalogOut + point*2, Format: "float32", Writable: true}
				tag.Role, tag.Init = "output", 0.0
			default:
				continue
			}
			b.Name, b.Source = name, opts.ID
			out.Manifest.Tags = append(out.Manifest.Tags, b)
			out.Tags = append(out.Tags, tag)
		}
	}
	if len(out.Manifest.Tags) == 0 {
		return Output{}, fmt.Errorf("optommp: the chassis reports no configured I/O channel")
	}
	if err := out.Manifest.Validate(); err != nil {
		return Output{}, fmt.Errorf("optommp: generated an invalid manifest:\n%w", err)
	}
	return out, nil
}

// TagsYAML renders the tag file with a header that says where it came from
// and how to regenerate it.
func TagsYAML(out Output, command, tagsPath string) ([]byte, error) {
	header := []string{
		fmt.Sprintf("Generated by `%s` from the processor's own chassis", command),
		"listing over OptoMMP. Do not edit — re-run the import after a module",
		"or channel-type change in groov Manage.",
		"",
		fmt.Sprintf("Compose it into a project with:  tag-files: [%s]", tagsPath),
	}
	return tagfile.Render(header, out.Tags)
}

// Command renders the generating invocation recorded in both files.
func Command(opts MapOptions) string {
	var b strings.Builder
	fmt.Fprintf(&b, "naut optommp import --host %s", opts.Host)
	if opts.ID != "EPIC" {
		fmt.Fprintf(&b, " --id %s", opts.ID)
	}
	if opts.Port != 0 && opts.Port != 502 {
		fmt.Fprintf(&b, " --modbus-port %d", opts.Port)
	}
	return b.String()
}
