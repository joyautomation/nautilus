package optommp

// generate.go turns a scanned chassis into the two files a nautilus project
// consumes for `driver: {type: optommp}`: optommp_manifest.yaml and a tag
// file to compose. Tag names are <ID>_M<slot>_<Kind><channel> — EPIC_M1_DO11
// — the same names the Modbus projection (modbusmap.go) uses, so a project
// moves from one to the other without touching its programs. Optional tags
// ride on the channel's name: _Count (a digital channel with a feature
// configured), _OnLatch / _OffLatch, _Quality; scratchpad tags are
// <ID>_SP_B<i> / _I<i> / _F<i>.

import (
	"fmt"
	"strconv"
	"strings"
	"time"

	"github.com/joyautomation/nautilus/internal/tagfile"
)

// ManifestOptions steer GenerateManifest.
type ManifestOptions struct {
	// ID is the tag-name prefix ("EPIC").
	ID string
	// Host and Port are what the driver dials (Port 0 = 2001).
	Host string
	Port int
	// ScanRate is written into the manifest when non-zero.
	ScanRate time.Duration
	// Latches adds _OnLatch and _OffLatch tags for every digital input.
	Latches bool
	// Quality adds a _Quality tag (the processor's code) for every analog channel.
	Quality bool
	// ScratchBits / ScratchInts / ScratchFloats add that many writable
	// scratchpad tags from element 0.
	ScratchBits, ScratchInts, ScratchFloats int
}

// GenerateManifest maps every configured I/O channel of the chassis onto a
// driver binding. Comm channels and unknown families are skipped. The
// result passes Manifest.Validate.
func GenerateManifest(ch Chassis, o ManifestOptions) (Manifest, error) {
	if o.ID == "" {
		return Manifest{}, fmt.Errorf("optommp: an id is required (the tag prefix)")
	}
	if o.Host == "" {
		return Manifest{}, fmt.Errorf("optommp: a host is required")
	}
	m := Manifest{Host: o.Host, Port: o.Port, ScanRate: Duration(o.ScanRate), Unit: ch.Part}
	for _, mod := range ch.Modules {
		info, _ := LookupModule(mod.Type)
		n := info.Channels
		if n == 0 {
			n = len(mod.Channels)
		}
		m.Modules = append(m.Modules, ModuleSpec{Slot: mod.Slot, Part: mod.Part, Type: Hex32(mod.Type), Channels: n})
		for _, c := range mod.Channels {
			base := fmt.Sprintf("%s_M%d_%s%02d", o.ID, mod.Slot, c.Kind, c.Index)
			b := Binding{Name: base, Slot: mod.Slot, Channel: c.Index, Type: c.Desc, Unit: c.Unit}
			if c.Name != "" {
				b.Desc = c.Name
			}
			switch c.Kind {
			case KindDI:
				b.Point = PointDI
			case KindDO:
				b.Point = PointDO
			case KindAI, KindAO:
				b.Point = PointAI
				if c.Kind == KindAO {
					b.Point = PointAO
				}
				if c.Lo != c.Hi {
					lo, hi := c.Lo, c.Hi
					b.Lo, b.Hi = &lo, &hi
				}
			default:
				continue
			}
			m.Tags = append(m.Tags, b)
			extra := func(suffix, point string) {
				m.Tags = append(m.Tags, Binding{Name: base + suffix, Point: point, Slot: mod.Slot, Channel: c.Index})
			}
			if (c.Kind == KindDI || c.Kind == KindDO) && c.Feature != 0 {
				extra("_Count", PointCounter)
			}
			if c.Kind == KindDI && o.Latches {
				extra("_OnLatch", PointOnLatch)
				extra("_OffLatch", PointOffLatch)
			}
			if (c.Kind == KindAI || c.Kind == KindAO) && o.Quality {
				extra("_Quality", PointQuality)
			}
		}
	}
	scratch := func(n int, letter, point string) {
		for i := 0; i < n; i++ {
			m.Tags = append(m.Tags, Binding{Name: fmt.Sprintf("%s_SP_%s%d", o.ID, letter, i), Point: point, Index: i, Writable: true})
		}
	}
	scratch(o.ScratchBits, "B", PointScratchBit)
	scratch(o.ScratchInts, "I", PointScratchInt)
	scratch(o.ScratchFloats, "F", PointScratchFloat)

	if len(m.Tags) == 0 {
		return Manifest{}, fmt.Errorf("optommp: the chassis reports no configured I/O channel")
	}
	v := m
	v.fillDefaults()
	if err := v.Validate(); err != nil {
		return Manifest{}, fmt.Errorf("optommp: generated an invalid manifest:\n%w", err)
	}
	return m, nil
}

// ManifestYAML renders the manifest with a header naming the command that
// made it. Byte-identical for an unchanged chassis.
func ManifestYAML(m Manifest, command string) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by `%s` from the processor's own\n", command)
	b.WriteString("# chassis listing over OptoMMP. Do not edit — re-run the import after a module\n")
	b.WriteString("# or channel-type change in groov Manage. `naut check` validates it offline.\n")
	fmt.Fprintf(&b, "host: %s\n", m.Host)
	if m.Port != 0 && m.Port != DefaultPort {
		fmt.Fprintf(&b, "port: %d\n", m.Port)
	}
	// Defaults are left out, so a parsed manifest renders as it was read.
	if r := time.Duration(m.ScanRate); r != 0 && r != DefaultScanRate {
		fmt.Fprintf(&b, "scan-rate: %s\n", r)
	}
	if to := time.Duration(m.Timeout); to != 0 && to != DefaultTimeout {
		fmt.Fprintf(&b, "timeout: %s\n", to)
	}
	if m.Unit != "" {
		fmt.Fprintf(&b, "unit: %s\n", yamlString(m.Unit))
	}
	if len(m.Modules) > 0 {
		b.WriteString("modules:\n")
		for _, mod := range m.Modules {
			fmt.Fprintf(&b, "  - { slot: %d, part: %s, type: %s, channels: %d }\n", mod.Slot, yamlString(mod.Part), mod.Type, mod.Channels)
		}
	}
	b.WriteString("tags:\n")
	for _, t := range m.Tags {
		fmt.Fprintf(&b, "  - { name: %s, point: %s", t.Name, t.Point)
		switch t.Point {
		case PointScratchBit, PointScratchInt, PointScratchFloat:
			fmt.Fprintf(&b, ", index: %d", t.Index)
		default:
			fmt.Fprintf(&b, ", slot: %d, channel: %d", t.Slot, t.Channel)
		}
		if t.Writable {
			b.WriteString(", writable: true")
		}
		if t.Type != "" {
			fmt.Fprintf(&b, ", type: %s", yamlString(t.Type))
		}
		if t.Unit != "" {
			fmt.Fprintf(&b, ", unit: %s", yamlString(t.Unit))
		}
		if t.Lo != nil {
			fmt.Fprintf(&b, ", lo: %s", strconv.FormatFloat(*t.Lo, 'g', -1, 64))
		}
		if t.Hi != nil {
			fmt.Fprintf(&b, ", hi: %s", strconv.FormatFloat(*t.Hi, 'g', -1, 64))
		}
		if t.Desc != "" {
			fmt.Fprintf(&b, ", desc: %s", yamlString(t.Desc))
		}
		b.WriteString(" }\n")
	}
	return []byte(b.String())
}

func yamlString(s string) string { return strconv.Quote(s) }

// ManifestTagsYAML renders the tag file for a manifest's bindings: outputs
// for the points the driver writes (seeded false / 0.0 / 0), inputs for
// the rest, each described from the module and channel type.
func ManifestTagsYAML(m Manifest, command, tagsPath string) ([]byte, error) {
	header := []string{
		fmt.Sprintf("Generated by `%s` from the processor's own chassis", command),
		"listing over OptoMMP. Do not edit — re-run the import after a module",
		"or channel-type change in groov Manage.",
		"",
		fmt.Sprintf("Compose it into a project with:  tag-files: [%s]", tagsPath),
	}
	parts := map[int]string{}
	for _, mod := range m.Modules {
		parts[mod.Slot] = mod.Part
	}
	var tags []tagfile.Tag
	for _, b := range m.Tags {
		t := tagfile.Tag{Name: b.Name, Role: "input", Unit: b.Unit}
		where := fmt.Sprintf("%s slot %d ch %d", parts[b.Slot], b.Slot, b.Channel)
		switch b.Point {
		case PointDI, PointDO, PointAI, PointAO:
			t.Desc = where + " — " + b.Type
			if b.Lo != nil && b.Hi != nil {
				t.Desc += fmt.Sprintf(" (%g to %g)", *b.Lo, *b.Hi)
			}
		case PointCounter:
			t.Desc = where + " — feature value (counter / totalizer)"
		case PointOnLatch:
			t.Desc = where + " — turned on since the previous scan"
		case PointOffLatch:
			t.Desc = where + " — turned off since the previous scan"
		case PointQuality:
			t.Desc = where + " — processor quality code, 0 = good"
		case PointScratchBit:
			t.Desc = fmt.Sprintf("scratchpad bit %d", b.Index)
		case PointScratchInt:
			t.Desc = fmt.Sprintf("scratchpad integer %d", b.Index)
		case PointScratchFloat:
			t.Desc = fmt.Sprintf("scratchpad float %d", b.Index)
		}
		if b.Desc != "" {
			t.Desc = b.Desc + " — " + t.Desc
		}
		if b.isOutput() {
			t.Role = "output"
			switch b.Point {
			case PointDO, PointScratchBit:
				t.Init = false
			case PointScratchInt:
				t.Init = int64(0)
			default:
				t.Init = 0.0
			}
		}
		tags = append(tags, t)
	}
	return tagfile.Render(header, tags)
}

// ManifestCommand renders the generating invocation recorded in both files.
func ManifestCommand(o ManifestOptions) string {
	var b strings.Builder
	fmt.Fprintf(&b, "naut optommp import --host %s", o.Host)
	if o.ID != "EPIC" {
		fmt.Fprintf(&b, " --id %s", o.ID)
	}
	if o.Port != 0 && o.Port != DefaultPort {
		fmt.Fprintf(&b, " --port %d", o.Port)
	}
	if o.ScanRate != 0 {
		fmt.Fprintf(&b, " --scan-rate %s", o.ScanRate)
	}
	if o.Latches {
		b.WriteString(" --latches")
	}
	if o.Quality {
		b.WriteString(" --quality")
	}
	if o.ScratchBits > 0 {
		fmt.Fprintf(&b, " --scratch-bits %d", o.ScratchBits)
	}
	if o.ScratchInts > 0 {
		fmt.Fprintf(&b, " --scratch-ints %d", o.ScratchInts)
	}
	if o.ScratchFloats > 0 {
		fmt.Fprintf(&b, " --scratch-floats %d", o.ScratchFloats)
	}
	return b.String()
}
