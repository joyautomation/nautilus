// generate.go dispatches to a profile (only "node" so far) and renders its
// result to bytes: prometheus_manifest.yaml by hand (modbus/codegen's
// convention — deterministic, reviewable, and pinned by a round-trip test)
// and tags/prometheus.yaml via internal/tagfile, the shared renderer every
// generator uses.
package codegen

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/joyautomation/nautilus/hw"
	"github.com/joyautomation/nautilus/internal/tagfile"
	"github.com/joyautomation/nautilus/prom"
)

// Options steers one generation.
type Options struct {
	// Tag is the source id AND the tag prefix every generated struct tag is
	// named from ("NODE1" → "NODE1", "NODE1_Fan1", "NODE1_Temp_CPU_Core_0").
	Tag string
	// URL is the scrape URL recorded into the manifest's one source.
	URL string
	// Profile selects the metric-to-member mapping; "" means "node" (the
	// only one this package ships).
	Profile string
}

// Output is one generation's result.
type Output struct {
	Manifest prom.Manifest
	// Desc is tag name → one-line description, for the tag file; codegen's
	// own bookkeeping, not carried by prom.Manifest itself.
	Desc map[string]string
}

// Generate builds the manifest (and its tag-file metadata) from one parsed
// scrape. Deterministic: same scrape in, same Output out, regardless of
// scrape.Samples' order (every enumeration here sorts before it renders).
func Generate(scrape prom.Scrape, opts Options) (Output, error) {
	if opts.Tag == "" {
		return Output{}, fmt.Errorf("codegen: --tag is required")
	}
	if opts.URL == "" {
		return Output{}, fmt.Errorf("codegen: --url is required")
	}
	profile := opts.Profile
	if profile == "" {
		profile = "node"
	}
	switch profile {
	case "node":
		return generateNode(scrape, opts)
	}
	return Output{}, fmt.Errorf("codegen: unknown profile %q (have: node)", profile)
}

